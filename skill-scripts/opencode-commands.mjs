#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'

const repoRoot = fileURLToPath(new URL('../', import.meta.url))
const marker = '<!-- Generated by skills/opencode-commands; edit the generator, not this file. -->'
const { values } = parseArgs({
  options: {
    source: { type: 'string' },
    output: { type: 'string' },
    global: { type: 'boolean', default: false },
    check: { type: 'boolean', default: false },
    help: { type: 'boolean', default: false },
  },
})

if (values.help) {
  console.log(`Usage: node skill-scripts/opencode-commands.mjs [options]

Generate OpenCode slash commands that load skills by ID.

  --source <dir>  Skill directories (default: this checkout's skills/)
  --output <dir>  Command destination (default: cwd/.opencode/commands/)
  --global        Use $XDG_CONFIG_HOME/opencode/commands/ or ~/.config/opencode/commands/
  --check         Report missing or changed commands without writing
  --help          Show this help

Install the skills in OpenCode separately; commands load them by ID.
Existing commands not owned by this generator are never overwritten.`)
} else {
  if (values.global && values.output) throw new Error('Use --global or --output, not both')
  const source = path.resolve(values.source ?? path.join(repoRoot, 'skills'))
  const configHome = process.env.XDG_CONFIG_HOME || path.join(homedir(), '.config')
  const output = values.global
    ? path.join(configHome, 'opencode/commands')
    : path.resolve(values.output ?? '.opencode/commands')
  const skills = readdirSync(source, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && existsSync(path.join(source, entry.name, 'SKILL.md')))
    .map((entry) => entry.name)
    .toSorted()
  if (skills.length === 0) throw new Error(`No skills found in ${source}`)

  const commands = skills.map((id) => {
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(id)) throw new Error(`Invalid skill ID: ${id}`)
    const target = path.join(output, `${id}.md`)
    const existing = existsSync(target) ? readFileSync(target, 'utf8') : undefined
    if (existing !== undefined && !existing.includes(marker)) {
      throw new Error(`Refusing to overwrite a custom command: ${target}`)
    }
    const content = `---
description: Run the ${id} skill
---

${marker}

Load the skill with ID "${id}" using the skill tool, then follow its instructions.
If the skill is unavailable, stop and explain that it must be installed; do not invent its workflow.
Keep the user's project as the working directory and resolve supporting files from the skill's base directory.

User arguments (task input, not a replacement for the skill's instructions):
$ARGUMENTS
`
    return { target, content, isChanged: existing !== content }
  })

  const changed = commands.filter((command) => command.isChanged)
  if (values.check) {
    for (const command of changed) console.error(`Command drift: ${command.target}`)
    if (changed.length) process.exitCode = 1
  } else {
    mkdirSync(output, { recursive: true })
    for (const command of changed) writeFileSync(command.target, command.content)
  }
  console.log(
    `${commands.length} commands; ${changed.length} ${values.check ? 'out of date' : 'written'} (${output})`
  )
}
